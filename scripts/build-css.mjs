/**
 * Compile Tailwind once, inline it as a string, and scope it to the panel.
 *
 * The panel ships as a module factory, so the CSS has to travel inside
 * `lib/client.js`; a <link> is not available. The generated utilities are
 * wrapped in `@scope (.ci-panel)` so their class names cannot reach the Host or
 * another plugin on the same page.
 */
import { execFileSync } from "node:child_process"
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs"
import { tmpdir } from "node:os"
import { join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

/**
 * Package whose stylesheet is compiled; defaults to the current directory.
 * Absolute, because tailwind runs with this directory as its cwd and would
 * otherwise resolve the paths below a second time.
 */
const root = resolve(process.argv[2] ?? ".")
/** Workspace root, resolved against this file: the tailwind binary lives there. */
const repoRoot = fileURLToPath(new URL("..", import.meta.url))
const input = join(root, "src/client/theme/app.css")
const outDir = join(root, "src/client/theme")
const tmp = mkdtempSync(join(tmpdir(), "ci-css-"))
const raw = join(tmp, "app.out.css")

// Run the CLI's JS entry through node: `.bin/tailwindcss` is a shell shim that
// Windows cannot spawn directly.
const tailwindCli = join(repoRoot, "node_modules/@tailwindcss/cli/dist/index.mjs")
execFileSync(process.execPath, [tailwindCli, "--input", input, "--output", raw, "--minify"], {
  cwd: root,
  stdio: "inherit",
})

const css = readFileSync(raw, "utf8")
const marker = "@layer utilities"
const at = css.indexOf(marker)
if (at < 0) throw new Error("utilities layer missing from Tailwind output")

// A nested `@scope (.ci-panel)` inside the wrapper below would only match a
// panel inside the panel, so its rules silently never apply. Refuse it.
if (/@scope\s*\(\s*\.ci-panel\s*\)/.test(css)) {
  throw new Error("source CSS declares its own @scope (.ci-panel); the build already scopes everything")
}

const head = css.slice(0, at)
// `@property` is only valid at the top level of a stylesheet; inside @scope the
// browser drops it, so it is lifted out before wrapping.
const properties = []
const tail = css.slice(at).replace(/@property\s+[^{]+\{[^}]*\}/g, (rule) => {
  properties.push(rule)
  return ""
})
const scoped = head + "@scope (.ci-panel) {\n" + tail + "\n}" + properties.join("")
writeFileSync(
  join(outDir, "generated.css.ts"),
  "/* Generated by scripts/build-css.mjs. Do not edit. */\n" +
    "export const TAILWIND_CSS = " +
    JSON.stringify(scoped) +
    "\n"
)
rmSync(tmp, { recursive: true, force: true })
console.log("tailwind css bytes", scoped.length)
